from playwright.sync_api import sync_playwright
errs=[]
P='file:///home/claude/practical-cybersecurity-for-the-modern-workplace/courses/12-file-sharing.html'
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':1440,'height':1000},device_scale_factor=2)
    pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(P); pg.wait_for_timeout(700)
    print('title:',pg.inner_text('h1'),'| nodes:',pg.locator('.node').count(),'| deep dives:',pg.locator('.more').count())
    print('share rows:',pg.locator('.sh-row').count(),'| go disabled:',pg.locator('#shgo-0').is_disabled())
    pg.screenshot(path='build/c12-share.png')
    pg.locator('[data-sh="0-0-2"]').click(); pg.wait_for_timeout(200)
    pg.locator('[data-sh="0-1-0"]').click(); pg.wait_for_timeout(200)
    print('still disabled after 2:',pg.locator('#shgo-0').is_disabled())
    pg.locator('[data-sh="0-2-1"]').click(); pg.wait_for_timeout(250)
    print('enabled after 3:',not pg.locator('#shgo-0').is_disabled())
    pg.locator('[data-shgo="0"]').click(); pg.wait_for_timeout(900)
    print('verdict:',pg.inner_text('#shn-0'))
    print('rows revealed:',pg.locator('.sh-row.done').count(),'| feedback:',pg.locator('#shfb-0.show').count()==1)
    print('xp:',pg.inner_text('#xp'))
    pg.evaluate("document.querySelector('.sh-dlg').scrollIntoView({block:'start'})"); pg.wait_for_timeout(400)
    pg.screenshot(path='build/c12-share-done.png')
    pg.locator('[data-opt="1"][data-j="1"]').dispatch_event('click'); pg.wait_for_timeout(1100)
    pg.locator('[data-opt="2"][data-j="0"]').dispatch_event('click'); pg.wait_for_timeout(1100)
    pg.locator('[data-exp="3"]').first.dispatch_event('click'); pg.wait_for_timeout(1400)
    print('end unlocked:',not pg.locator('.endcard').evaluate('e=>e.classList.contains("locked")'))
    h=pg.evaluate("document.getElementById('track').scrollHeight"); print('height:',round(h/1000,1),'screens')
    print('takeaways:',pg.locator('.ec-t').count(),'| sources:',pg.locator('.ec-src').count())
    pg2=b.new_page(viewport={'width':390,'height':844},device_scale_factor=2)
    pg2.goto(P); pg2.wait_for_timeout(600)
    print('mobile h-scroll:',pg2.evaluate("document.documentElement.scrollWidth>document.documentElement.clientWidth"))
    pg2.screenshot(path='build/c12-mobile.png')
    b.close()
print('errors:',errs or 'none')
