from playwright.sync_api import sync_playwright
errs=[]
P='file:///home/claude/practical-cybersecurity-for-the-modern-workplace/courses/11-data-classification.html'
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':1440,'height':900})
    pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(P); pg.wait_for_timeout(700)
    print('title:',pg.inner_text('h1'),'| nodes:',pg.locator('.node').count(),'| deep dives:',pg.locator('.more').count())
    print('trace stops:',pg.locator('[id^="tr-0-"]').count())
    for j in range(3):
        pg.locator(f'[data-trace="0-{j}"]').dispatch_event('click'); pg.wait_for_timeout(450)
    pg.wait_for_timeout(900)
    print('all stops open:',pg.locator('[id^="tr-0-"].done').count())
    print('trace feedback:',pg.locator('#trfb-0.show').count()==1)
    bars=pg.evaluate("[...document.querySelectorAll('[id^=\"tr-0-\"] .tr-bar i')].map(x=>x.style.width)")
    print('reach bars:',bars)
    pg.locator('[data-opt="1"][data-j="1"]').dispatch_event('click'); pg.wait_for_timeout(1100)
    pg.locator('[data-opt="2"][data-j="1"]').dispatch_event('click'); pg.wait_for_timeout(1100)
    pg.locator('[data-exp="3"]').first.dispatch_event('click'); pg.wait_for_timeout(1400)
    print('end unlocked:',not pg.locator('.endcard').evaluate('e=>e.classList.contains("locked")'))
    print('xp:',pg.inner_text('#xp'))
    h=pg.evaluate("document.getElementById('track').scrollHeight"); print('height:',round(h/900,1),'screens')
    txt=pg.evaluate("document.getElementById('track').innerText"); print('total words:',len(txt.split()))
    pg.locator('[data-check="4-0"]').dispatch_event('click'); pg.wait_for_timeout(400)
    print('plan items:',pg.locator('#yourplan li').count())
    print('takeaways:',pg.locator('.ec-t').count(),'| sources:',pg.locator('.ec-src').count())
    pg.evaluate("document.querySelector('[id^=\"tr-0-\"]').scrollIntoView({block:'start'})"); pg.wait_for_timeout(400)
    pg.screenshot(path='build/c11-trace.png')
    pg2=b.new_page(viewport={'width':390,'height':844},device_scale_factor=2)
    pg2.goto(P); pg2.wait_for_timeout(700)
    print('mobile h-scroll:',pg2.evaluate("document.documentElement.scrollWidth>document.documentElement.clientWidth"))
    pg2.locator('[data-trace="0-1"]').dispatch_event('click'); pg2.wait_for_timeout(600)
    pg2.screenshot(path='build/c11-mobile.png')
    b.close()
print('errors:',errs or 'none')
